"""
One-command initialisation of a ClearClaim database.

    python scripts/setup_demo.py                 # demo mode: synthetic data (generated if missing)
    python scripts/setup_demo.py --reset         # wipe ClearClaim tables first
    python scripts/setup_demo.py --source mimic  # real MIMIC-IV files in data/mimic_iv/demo (see README.md, MIMIC-IV section)
    python scripts/setup_demo.py --no-process    # import only; process from the UI

Steps: seed the 59 cited rules (legacy seeder) -> Alembic migrations for ClearClaim
tables -> import encounters (ground truth is never imported) -> build the RAG
index -> process all NEW cases. Uses DATABASE_URL (default: backend/claim_validator.db).
"""
import argparse
import contextlib
import io
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKEND = os.path.join(ROOT, "backend")
sys.path.insert(0, BACKEND)
os.chdir(BACKEND)  # the default SQLite URL is relative to backend/


def mask_url(url: str) -> str:
    """Never print database passwords."""
    import re
    return re.sub(r"(://[^:/@]+:)[^@]*@", r"\1***@", url)


def needs_generation(data_dir: str) -> bool:
    """True if the generated dataset is missing or was written by another generator version."""
    import json
    from app.datasets.synthetic import GENERATOR_VERSION
    path = os.path.join(data_dir, "MANIFEST.json")
    if not os.path.exists(path):
        return True
    with open(path, encoding="utf-8") as f:
        found = json.load(f).get("generator_version")
    if found != GENERATOR_VERSION:
        print(f"{data_dir} was generated by v{found}; regenerating with v{GENERATOR_VERSION}.")
        return True
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", choices=["demo", "mimic"], default=os.environ.get("DATA_MODE", "demo"))
    ap.add_argument("--reset", action="store_true")
    ap.add_argument("--no-process", action="store_true")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--max-encounters", type=int, default=None)
    ap.add_argument("--reseed-rules", action="store_true",
                    help="Re-seed the 59 rules even if present. WARNING: the legacy seeder drops ALL legacy "
                         "validator tables, including claims entered in the legacy UI.")
    ap.add_argument("--rebuild-rag", action="store_true", help="Rebuild the policy explainer index")
    a = ap.parse_args()

    from app.clearclaim.config import settings
    from app.database import seed
    from app.database.db import SessionLocal, engine
    from app.clearclaim.models import CCBase, ClaimCase
    from app.clearclaim.server import migrate
    from app.clearclaim.etl import import_dataset
    from app.clearclaim.orchestrator import Orchestrator
    from app.datasets.synthetic import generate_synthetic_dataset, generate_admin_layer_for_mimic

    print(f"Database: {mask_url(settings.database_url)}")
    from sqlalchemy import inspect, text
    insp = inspect(engine)
    has_rules = "policy_rules" in insp.get_table_names()
    if has_rules:
        with engine.connect() as c:
            has_rules = (c.execute(text("SELECT COUNT(*) FROM policy_rules")).scalar() or 0) > 0
    if a.reseed_rules or not has_rules:
        # The legacy seeder drops and recreates every legacy table, so it only runs when the
        # rules are missing (fresh database) or when explicitly requested.
        with contextlib.redirect_stdout(io.StringIO()) as buf:
            seed.run()
        print(buf.getvalue().strip())
    else:
        print("Rules already seeded; legacy tables left untouched (use --reseed-rules to force).")
    if a.reset:
        CCBase.metadata.drop_all(engine)
        with engine.begin() as c:
            c.exec_driver_sql("DROP TABLE IF EXISTS alembic_version")
        print("ClearClaim tables dropped.")
    migrate()
    print("Migrations applied.")

    if a.source == "demo":
        data_dir = settings.demo_dataset_dir
        if needs_generation(data_dir):
            print(f"Generating synthetic demo dataset in {data_dir} ...")
            generate_synthetic_dataset(data_dir, seed=a.seed, n_encounters=a.n)
        clinical, admin, label = data_dir, data_dir, "SYNTHETIC"
    else:
        clinical, admin, label = settings.mimic_clinical_dir, settings.mimic_admin_dir, settings.mimic_source_label
        from app.datasets.mimic import table_path
        if table_path(clinical, "hosp", "admissions") is None:
            sys.exit(f"No MIMIC-IV files in {clinical}. See the MIMIC-IV section of README.md for download instructions.")
        if needs_generation(admin):
            print("Generating the synthetic insurance/admin layer for the real MIMIC encounters ...")
            generate_admin_layer_for_mimic(clinical, admin, seed=a.seed, source_label=label,
                                           max_encounters=a.max_encounters)

    db = SessionLocal()
    imp = import_dataset(db, clinical, admin, a.source, label, max_encounters=a.max_encounters)
    print(f"Import #{imp.id}: {imp.status}, {imp.n_encounters} new encounter(s); "
          f"{len(imp.validation_report['errors'])} validation error(s), {len(imp.validation_report['warnings'])} warning(s)")
    if imp.status != "COMPLETED":
        for e in imp.validation_report["errors"][:20]:
            print("  ERROR:", e)
        sys.exit(1)

    rag_dir = os.path.join(ROOT, "data", "processed", "chunks")
    rag_present = all(os.path.exists(os.path.join(rag_dir, f)) for f in ("chunks.json", "tfidf_matrix.pkl",
                                                                          "tfidf_vectorizer.pkl"))
    if rag_present and not a.rebuild_rag:
        print("RAG policy index present (use --rebuild-rag to rebuild).")
    else:
        try:
            import runpy
            with contextlib.redirect_stdout(io.StringIO()):
                runpy.run_path(os.path.join(ROOT, "scripts", "build_rag_index.py"), run_name="__main__")
            print("RAG policy index built.")
        except BaseException as e:  # explainer is optional; report and continue
            print(f"RAG index not built ({type(e).__name__}: {e}); the policy explainer will report unavailable.")

    if not a.no_process:
        cases = db.query(ClaimCase).filter_by(status="NEW").order_by(ClaimCase.id).all()
        t0 = time.perf_counter()
        orch = Orchestrator(db)
        for c in cases:
            orch.process(c)
        print(f"Processed {len(cases)} case(s) in {time.perf_counter() - t0:.1f}s.")
    from collections import Counter
    print("Case status:", dict(Counter(c.status for c in db.query(ClaimCase))))
    db.close()


if __name__ == "__main__":
    main()
