import { Fragment } from 'react';
import { api } from '../../lib/api';
import { useApi } from '../../lib/hooks';
import { dateTime, humanize, n } from '../../lib/format';
import { Badge, Card, EmptyState, ErrorState, PageHead, Skeleton } from '../../components/ui';
import { BarList } from '../../components/charts';

/* eslint-disable @typescript-eslint/no-explicit-any */
export default function DataLab() {
  const { data, error, reload } = useApi<any>(() => api.dataStatus());
  const exps = useApi<any[]>(() => api.experiments());
  const latest = (exps.data || []).find((e) => e.status === 'COMPLETED' && e.has_summary);
  const latestDetail = useApi<any>(() => (latest ? api.experiment(latest.id) : Promise.resolve(null)), [latest?.id]);

  if (error) return <><PageHead title="Data laboratory" /><ErrorState message={error} onRetry={reload} /></>;
  if (!data) return <><PageHead title="Data laboratory" /><Skeleton rows={6} /></>;
  const active = data.imports.find((i: any) => i.status === 'COMPLETED');
  const scen = latestDetail.data?.summary?.per_seed && Object.values(latestDetail.data.summary.per_seed)[0] as any;

  return (
    <>
      <PageHead title="Data laboratory" sub="Where the data comes from, how it was generated, and whether it passed validation." />
      <div className="stack">
        <div className="grid g-3">
          <Card title="Data mode">
            <div className="row"><span className="badge b-accent">{data.data_mode}</span>
              {data.mimic_files_present ? <Badge value="SUCCEEDED" title="MIMIC files found" /> : <span className="badge b-review">MIMIC-IV files not present</span>}</div>
            <p className="small muted">{data.mimic_files_present ? 'Authorised MIMIC-IV files are available locally.' :
              <>Real-data evaluation is pending. Download the open MIMIC-IV Clinical Database Demo v2.2 (see <span className="mono">{data.mimic_instructions}</span>) or use credentialed MIMIC-IV v3.1.</>}</p>
          </Card>
          <Card title="Encounters by source">
            {Object.keys(data.encounters_by_source).length === 0 ? <EmptyState title="Nothing imported" /> :
              <BarList label="Encounters by source" items={Object.entries(data.encounters_by_source).map(([k, v]) => ({ key: k, label: k, value: v as number }))} />}
          </Card>
          <Card title="Live data-quality findings" meta="current, intake stages">
            {data.live_data_quality.length === 0 ? <EmptyState title="No data-quality findings" /> :
              <BarList label="Data quality findings" items={data.live_data_quality.map((x: any) => ({ key: x.code + x.severity, label: humanize(x.code), value: x.count, sub: x.severity.toLowerCase() }))} />}
          </Card>
        </div>

        <Card title="Active dataset" meta={active ? `import #${active.id} · ${dateTime(active.imported_at)}` : ''}>
          {!active ? <EmptyState title="No dataset imported">Run <span className="mono">python scripts/setup_demo.py</span></EmptyState> : (
            <div className="grid g-2">
              <dl className="kv">
                <dt>Source</dt><dd>{active.source_label} <span className="faint small">({active.mode} mode)</span></dd>
                <dt>Generator</dt><dd>{active.manifest_mode} · v{active.generator_version}</dd>
                <dt>Parameters</dt><dd className="mono small">{JSON.stringify(active.parameters)}</dd>
                <dt>Encounters</dt><dd>{n(active.n_encounters, 0)}</dd>
                <dt>Manifest SHA-256</dt><dd className="mono small">{active.manifest_sha256?.slice(0, 24)}…</dd>
              </dl>
              <div>
                <div className="row" style={{ marginBottom: 6 }}><strong className="small">Validation</strong>
                  <span className={`badge ${active.validation.errors.length ? 'b-blocked' : 'b-complete'}`}>{active.validation.errors.length} errors</span>
                  <span className="badge b-info">{active.validation.warnings.length} warnings</span></div>
                <dl className="kv small">{Object.entries(active.validation.stats).map(([k, v]) => <Fragment key={k}><dt>{humanize(k)}</dt><dd className="mono">{typeof v === 'object' ? JSON.stringify(v) : String(v)}</dd></Fragment>)}</dl>
                {active.validation.warnings.map((w: string, i: number) => <div key={i} className="small faint">⚠ {w}</div>)}
              </div>
            </div>)}
        </Card>

        <div className="grid g-2">
          <Card title="Reproducible generation">
            <p className="small muted">Synthetic data is generated by a seeded script; the same seed and parameters produce byte-identical files (verified by tests). Ground-truth labels are written to a separate folder and are never imported into the application.</p>
            <pre className="note-text">{`python scripts/generate_synthetic_data.py --seed 42 --n-encounters 200 --error-rate 0.35
python scripts/validate_encounter_data.py
python scripts/setup_demo.py --reset`}</pre>
          </Card>
          <Card title="Scenario distribution" meta={latest ? `from experiment #${latest.id} (aggregate only)` : ''}>
            {!scen ? <EmptyState title="Run an experiment to see the evaluated cohort" /> :
              <BarList label="Scenario classes" items={Object.entries(scen.scenario_classes).map(([k, v]) => ({ key: k, label: humanize(k), value: v as number }))} />}
            <div className="small faint" style={{ marginTop: 8 }}>Per-case labels are deliberately not shown in the application.</div>
          </Card>
        </div>
      </div>
    </>
  );
}
